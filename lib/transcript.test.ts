import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import type { SessionMessage } from "@anthropic-ai/claude-agent-sdk";
import { describe, expect, it } from "vitest";

// Pasted images and shown local files are copied into the attachments folder, so point the store
// at a temp one before importing.
const data = fs.mkdtempSync(path.join(os.tmpdir(), "weft-transcript-"));
process.env.THREADBOARD_DATA = data;

const { transcriptToThread, typedPromptOf } = await import("./transcript");

type Msg = Record<string, unknown>;
const user = (content: unknown, extra: Msg = {}): Msg => ({ type: "user", message: { content }, ...extra });
const assistant = (content: unknown, extra: Msg = {}): Msg => ({ type: "assistant", message: { content }, ...extra });
const thread = (messages: Msg[], options?: Parameters<typeof transcriptToThread>[1]) =>
  transcriptToThread(messages as unknown as SessionMessage[], options);

// A 1x1 transparent PNG.
const PNG = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII=";
const imageBlock = { type: "image", source: { type: "base64", media_type: "image/png", data: PNG } };

describe("typedPromptOf", () => {
  it("returns what the user typed, from a string or from text blocks", () => {
    expect(typedPromptOf(user("fix the build"))).toBe("fix the build");
    expect(typedPromptOf(user([{ type: "text", text: "one" }, { type: "text" }, imageBlock, null, { type: "text", text: "two" }]))).toBe("one\n\ntwo");
  });

  it("is empty for anything that isn't a prompt the user typed", () => {
    expect(typedPromptOf(assistant("hi"))).toBe("");
    expect(typedPromptOf(user("hi", { isSidechain: true }))).toBe("");
    expect(typedPromptOf(user("hi", { isMeta: true }))).toBe("");
    expect(typedPromptOf(user("hi", { isCompactSummary: true }))).toBe("");
    expect(typedPromptOf(user("hi", { origin: { kind: "task-notification" } }))).toBe("");
    expect(typedPromptOf(user("hi", { origin: { kind: "peer" } }))).toBe("");
    expect(typedPromptOf({ type: "user" })).toBe("");
    expect(typedPromptOf(user({ not: "blocks" }))).toBe("");
  });

  it("keeps a prompt from an origin that isn't the CLI", () => {
    expect(typedPromptOf(user("hi", { origin: { kind: "human" } }))).toBe("hi");
  });

  it("strips reminders and hook output embedded in the text", () => {
    expect(typedPromptOf(user("<system-reminder>be nice</system-reminder>deploy it"))).toBe("deploy it");
    expect(typedPromptOf(user("ship <user-prompt-submit-hook>clock 10:00</user-prompt-submit-hook>"))).toBe("ship");
    expect(typedPromptOf(user("<system-reminder>only this</system-reminder>  "))).toBe("");
  });

  it("drops text the CLI injected", () => {
    for (const text of [
      "[Request interrupted by user]",
      "Caveat: The messages below were generated by the user while running local commands.",
      "<local-command-stdout>ok</local-command-stdout>",
      "<task-notification>done</task-notification>",
      "<bash-stdout>files</bash-stdout>",
    ]) {
      expect(typedPromptOf(user(text))).toBe("");
    }
  });

  it("reads a slash command back from the CLI's tags", () => {
    const cmd = (name: string, args = "") =>
      `<command-message>${name} is running</command-message>\n<command-name>${name}</command-name>\n<command-args>${args}</command-args>`;
    expect(typedPromptOf(user(cmd("/commit", " fix the build ")))).toBe("/commit fix the build");
    expect(typedPromptOf(user(cmd("weft:done")))).toBe("/weft:done");
    expect(typedPromptOf(user("<command-message>no name</command-message>"))).toBe("");
  });

  it("drops local commands like /model, which only changed the CLI", () => {
    expect(typedPromptOf(user("<command-name>/model</command-name>", { isCompletedLocalCommand: true }))).toBe("");
  });

  it("shows a ! bash command as the user typed it", () => {
    expect(typedPromptOf(user("<bash-input> ls -la </bash-input>"))).toBe("! ls -la");
  });
});

describe("transcriptToThread", () => {
  it("turns prompts and replies into user and assistant items, with their times", () => {
    const items = thread([
      user("hello", { timestamp: "2026-10-01T10:00:00.000Z" }),
      assistant([{ type: "text", text: "Hi there" }], { timestamp: "2026-10-01T10:00:05.000Z" }),
    ]);
    expect(items).toEqual([
      { kind: "user", text: "hello", at: Date.parse("2026-10-01T10:00:00.000Z") },
      { kind: "assistant", text: "Hi there", at: Date.parse("2026-10-01T10:00:05.000Z") },
    ]);
  });

  it("uses 0 for a missing or unreadable timestamp", () => {
    const items = thread([user("a"), user("b", { timestamp: "not a date" })]);
    expect(items.map((i) => i.at)).toEqual([0, 0]);
  });

  it("strips the BOARD STATUS line and review block from replies, and drops replies left empty", () => {
    const review = '```weft-review\n{"steps":[{"title":"Open it"}]}\n```';
    const items = thread([
      assistant([{ type: "text", text: `Built it.\n\n${review}\nBOARD STATUS: column=review | stage=First shot` }]),
      assistant([{ type: "text", text: "BOARD STATUS: column=done" }]),
      assistant([{ type: "text" }]),
    ]);
    expect(items).toEqual([{ kind: "assistant", text: "Built it.", at: 0 }]);
  });

  it("drops the CLI's synthetic filler after an interrupt, but not a real reply saying the same", () => {
    const filler = [{ type: "text", text: "No response requested." }];
    const items = thread([{ type: "assistant", message: { model: "<synthetic>", content: filler } }, assistant(filler)]);
    expect(items).toEqual([{ kind: "assistant", text: "No response requested.", at: 0 }]);
  });

  it("attaches each tool's result to its call, with errors flagged", () => {
    const items = thread([
      assistant([
        { type: "tool_use", id: "t1", name: "Bash", input: { command: "npm test" } },
        { type: "tool_use", id: "t2", name: "Read", input: { file_path: "/a.ts" } },
      ]),
      user([
        { type: "tool_result", tool_use_id: "t1", content: "all green" },
        { type: "tool_result", tool_use_id: "t2", content: [{ type: "text", text: "no such file" }], is_error: true },
      ]),
    ]);
    expect(items).toEqual([
      { kind: "tool", id: "t1", name: "Bash", summary: "npm test", action: "command", at: 0, result: "all green", isError: false },
      { kind: "tool", id: "t2", name: "Read", summary: "/a.ts", action: "read", at: 0, result: "no such file", images: undefined, isError: true },
    ]);
  });

  it("names a tool call with no name or input, and skips one without an id", () => {
    const items = thread([assistant([{ type: "tool_use", id: "t1" }, { type: "tool_use", name: "Bash" }])]);
    expect(items).toEqual([{ kind: "tool", id: "t1", name: "tool", summary: "", action: "use:tool", at: 0 }]);
  });

  it("ignores results for unknown calls, and results with no call id", () => {
    const items = thread([
      assistant([{ type: "tool_use", id: "t1", name: "Bash", input: {} }]),
      user([{ type: "tool_result", tool_use_id: "nope", content: "x" }, { type: "tool_result", content: "y" }]),
    ]);
    expect(items).toHaveLength(1);
    expect(items[0]).not.toHaveProperty("result");
  });

  it("closes a tool call the conversation moved on from, but leaves the last one running", () => {
    const items = thread([
      assistant([{ type: "tool_use", id: "cut", name: "Bash", input: {} }]),
      user("[Request interrupted by user for tool use]"),
      user("try again"),
      assistant([{ type: "tool_use", id: "live", name: "Bash", input: {} }]),
    ]);
    expect(items.map((i) => (i.kind === "tool" ? [i.id, i.result] : [i.kind]))).toEqual([["cut", ""], ["user"], ["live", undefined]]);
  });

  it("leaves out subagent turns, CLI-sent user messages, and other message types", () => {
    const items = thread([
      assistant([{ type: "text", text: "from a subagent" }], { parent_tool_use_id: "task-1" }),
      user("reminder", { is_meta: true }),
      user("summary of earlier", { isCompactSummary: true }),
      user("a peer said hi", { origin: { kind: "peer" } }),
      { type: "system", message: { content: "init" } },
      { type: "user" },
      user("mine"),
    ]);
    expect(items).toEqual([{ kind: "user", text: "mine", at: 0 }]);
    expect(thread([user([{ type: "text" }])])).toEqual([]);
  });

  it("adds images pasted into Claude Code to the prompt as attachment refs", () => {
    const item = thread([user([imageBlock, { type: "text", text: "what is this?" }])])[0]!;
    expect(item.kind).toBe("user");
    const text = item.kind === "user" ? item.text : "";
    const ref = text.match(/^!\[pasted-image[^\]]*\]\((.+)\)\n\nwhat is this\?$/);
    expect(ref).not.toBeNull();
    expect(ref![1]!.startsWith(path.join(data, "attachments"))).toBe(true);
    expect(fs.existsSync(ref![1]!)).toBe(true);
  });

  it("doesn't add pasted images again when the text already refers to an attachment, as Weft's messages do", () => {
    const text = `look ![shot](${path.join(data, "attachments", "shot-1a2b3c4d.png")})`;
    expect(thread([user([{ type: "text", text }, imageBlock])])).toEqual([{ kind: "user", text, at: 0 }]);
  });

  it("copies a local image the assistant shows into the attachments folder, resolving it against cwd", () => {
    const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "weft-transcript-cwd-"));
    fs.writeFileSync(path.join(cwd, "chart.png"), Buffer.from(PNG, "base64"));
    const item = thread([assistant([{ type: "text", text: "Here: ![chart](chart.png)" }])], { cwd })[0]!;
    const text = item.kind === "assistant" ? item.text : "";
    expect(text).toMatch(new RegExp(`^Here: !\\[chart\\]\\(${path.join(data, "attachments")}/chart-[0-9a-f]+\\.png\\)$`));
  });

  it("keeps only the last maxItems items, 400 by default", () => {
    const many = Array.from({ length: 405 }, (_, i) => user(`p${i}`));
    expect(thread(many)).toHaveLength(400);
    expect(thread(many, { maxItems: 2 }).map((i) => (i.kind === "user" ? i.text : ""))).toEqual(["p403", "p404"]);
  });
});
